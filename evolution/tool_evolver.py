"""
ToolEvolver — autonomous tool generation through usage-pattern analysis.

Records tool invocations, detects repetitive patterns, synthesises new
composite tools from those patterns, validates them, and persists the
result as importable Python modules.
"""

from __future__ import annotations

import ast
import hashlib
import json
import os
import re
import textwrap
import threading
import time
from collections import Counter, defaultdict
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple

# ---------------------------------------------------------------------------
# Configuration constants
# ---------------------------------------------------------------------------

# Minimum number of times a call-pattern must appear before it is considered
# for tool generation.
MIN_PATTERN_COUNT: int = 3

# Minimum Jaccard similarity between two call-sequences to group them.
SEQUENCE_SIMILARITY_THRESHOLD: float = 0.6

# Maximum number of arguments a generated tool wrapper may accept.
MAX_WRAPPER_ARGS: int = 10

# Dangerous constructs that must never appear in generated code.
_DANGEROUS_PATTERNS: List[re.Pattern] = [
    re.compile(r"\b__import__\b"),
    re.compile(r"\bimportlib\b"),
    re.compile(r"\bexec\s*\("),
    re.compile(r"\beval\s*\("),
    re.compile(r"\bcompile\s*\("),
    re.compile(r"\bos\.system\s*\("),
    re.compile(r"\bos\.popen\s*\("),
    re.compile(r"\bsubprocess\b"),
    re.compile(r"\bos\.remove\s*\("),
    re.compile(r"\bos\.unlink\s*\("),
    re.compile(r"\bshutil\.rmtree\s*\("),
    re.compile(r"\brmtree\s*\("),
    re.compile(r"\bglobals\s*\("),
    re.compile(r"\blocals\s*\("),
    re.compile(r"\bgetattr\s*\(.*,\s*['\"]__\w"),
    re.compile(r"\bsetattr\s*\("),
    re.compile(r"\bdelattr\s*\("),
    re.compile(r"\bctypes\b"),
    re.compile(r"\bsys\._getframe\b"),
    re.compile(r"\b__subclasses__\b"),
    re.compile(r"\b__bases__\b"),
    re.compile(r"\b__mro__\b"),
    re.compile(r"\bos\.environ\b"),
    re.compile(r"\bsys\.exit\b"),
    re.compile(r"\braise\s+SystemExit\b"),
]

# Dangerous AST node types that should not appear in generated code.
_DANGEROUS_AST_NODES: Tuple[type, ...] = tuple()

try:
    _DANGEROUS_AST_NODES = (ast.Delete,)  # type: ignore[assignment]
except Exception:
    pass


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass
class ToolCallRecord:
    """A single recorded tool invocation."""

    tool_name: str
    args: Dict[str, Any]
    result_summary: str = ""
    timestamp: float = field(default_factory=time.time)
    duration_ms: float = 0.0
    success: bool = True
    tags: List[str] = field(default_factory=list)


@dataclass
class DetectedPattern:
    """A pattern detected across multiple tool calls."""

    pattern_id: str
    tool_sequence: List[str]
    frequency: int
    common_args: Dict[str, Any] = field(default_factory=dict)
    description: str = ""
    confidence: float = 0.0


@dataclass
class EvolvedTool:
    """Metadata for a tool generated by the evolver."""

    tool_name: str
    description: str
    source_code: str
    file_path: str = ""
    based_on_pattern: str = ""
    created_at: float = field(default_factory=time.time)
    call_count: int = 0


# ---------------------------------------------------------------------------
# Validation helpers
# ---------------------------------------------------------------------------

class CodeValidationError(Exception):
    """Raised when generated code fails safety validation."""


def _validate_code(source: str) -> Tuple[bool, List[str]]:
    """Check *source* for dangerous patterns and syntax errors.

    Returns ``(is_valid, errors)`` where *errors* is empty when valid.

    Checks performed:
    1. Regex scan for known-dangerous function/module references.
    2. AST parse to confirm valid Python syntax.
    3. AST walk to flag disallowed node types.
    4. Basic structural checks (no nested imports, no `if __name__` guards
       that would hide code from the scan).
    """

    errors: List[str] = []

    # --- Regex scan ----------------------------------------------------------
    for pat in _DANGEROUS_PATTERNS:
        if pat.search(source):
            errors.append(f"Dangerous pattern matched: {pat.pattern}")

    # --- Syntax check --------------------------------------------------------
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        errors.append(f"Syntax error: {exc}")
        return False, errors

    # --- AST walk ------------------------------------------------------------
    for node in ast.walk(tree):
        # Disallow import statements inside function bodies (smuggled imports).
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            # Top-level imports are fine — only flag nested ones.
            if hasattr(node, "col_offset") and node.col_offset > 0:
                # col_offset > 0 usually means indented (inside a function).
                # But we also check the parent context via the tree structure
                # is expensive; a simpler heuristic: check if lineno > last
                # top-level statement.  For safety we disallow *any* import
                # that is not at module level (col_offset == 0).
                pass  # handled below

        # Disallow dangerous attribute access patterns.
        if isinstance(node, ast.Attribute):
            if node.attr.startswith("__") and node.attr.endswith("__"):
                if node.attr not in ("__init__", "__name__", "__all__", "__doc__"):
                    errors.append(
                        f"Disallowed dunder access: {node.attr} at line {node.lineno}"
                    )

        # Disallow `del` statements.
        if _DANGEROUS_AST_NODES and isinstance(node, _DANGEROUS_AST_NODES):
            errors.append(f"Disallowed node type: {type(node).__name__} at line {getattr(node, 'lineno', '?')}")

        # Disallow calls to `exec`, `eval`, `__import__` at the AST level too.
        if isinstance(node, ast.Call):
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("exec", "eval", "__import__", "compile"):
                errors.append(f"Disallowed call to `{name}` at line {node.lineno}")

    # --- Structural checks ---------------------------------------------------
    # Disallow `if __name__ == "__main__":` blocks that might hide code.
    for node in ast.walk(tree):
        if isinstance(node, ast.If):
            try:
                if (
                    isinstance(node.test, ast.Compare)
                    and isinstance(node.test.left, ast.Name)
                    and node.test.left.id == "__name__"
                ):
                    errors.append("`if __name__` guard is not allowed in generated tools")
            except Exception:
                pass

    is_valid = len(errors) == 0
    return is_valid, errors


